using System.Text;
using System.Text.Json;
using System.Text.Encodings.Web;
using MeadowPeaks.Content;

bool check = args.Contains("--check");
string root = Path.GetFullPath(args.FirstOrDefault(a => a != "--check") ?? ".");
string target = Path.Combine(root, "web", "generated-content.mjs");
if (!Directory.Exists(Path.GetDirectoryName(target)))
    throw new ArgumentException("Pass the repository root containing web/.");

var ids = InterfaceCatalog.Features.Select(f => f.Id).ToHashSet();
if (ids.Count != InterfaceCatalog.Features.Length)
    throw new InvalidOperationException("Feature identifiers must be unique.");
foreach (var feature in InterfaceCatalog.Features)
    if (feature.Level < 1 || string.IsNullOrWhiteSpace(feature.Action) || string.IsNullOrWhiteSpace(feature.Icon))
        throw new InvalidOperationException($"Incomplete feature: {feature.Id}");
var members = InterfaceCatalog.ActivityGroups.SelectMany(g => g.Activities).ToArray();
if (members.Distinct().Count() != members.Length || members.Any(id => !ids.Contains(id)))
    throw new InvalidOperationException("Each grouped activity must reference one feature and have one parent.");
foreach (var (id, steps) in InterfaceCatalog.FeatureTutorials)
    if (!ids.Contains(id) || steps.Length == 0 || steps.Any(s => s.Length != 2 || s.Any(string.IsNullOrWhiteSpace)))
        throw new InvalidOperationException($"Invalid tutorial: {id}");

var options = new JsonSerializerOptions
{
    PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
    Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping
};
var output = new StringBuilder("// Generated by MeadowPeaks.ContentExporter from InterfaceCatalog.cs. Do not edit.\n");
void Export<T>(string name, T value) => output.Append("export const ").Append(name)
    .Append('=').Append(JsonSerializer.Serialize(value, options)).Append(";\n");
Export("features", InterfaceCatalog.Features);
Export("mechanicLessons", InterfaceCatalog.MechanicLessons);
Export("briefGuides", InterfaceCatalog.BriefGuides);
Export("explanations", InterfaceCatalog.Explanations);
Export("shortRules", InterfaceCatalog.ShortRules);
Export("shapes", InterfaceCatalog.SymbolPaths);
Export("featureTutorials", InterfaceCatalog.FeatureTutorials);
Export("activityGroups", InterfaceCatalog.ActivityGroups.Select(g => new object[] { g.Title, g.Icon, g.Activities }));
string expected = output.ToString();
if (check)
{
    if (!File.Exists(target) || File.ReadAllText(target).Replace("\r\n", "\n") != expected)
    {
        Console.Error.WriteLine("Browser content is stale. Run dotnet run --project tools/MeadowPeaks.ContentExporter -- .");
        return 1;
    }
    Console.WriteLine("PASS: browser content matches the validated C# catalog.");
}
else
{
    File.WriteAllText(target, expected, new UTF8Encoding(false));
    Console.WriteLine($"Generated {target}");
}
return 0;
